CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (role IN ('ADMIN', 'USER'))
);

CREATE TABLE account_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT NOT NULL,
    actor_username VARCHAR(64) NOT NULL,
    target_user_id BIGINT,
    action VARCHAR(48) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_account_audit_created_at ON account_audit_log (created_at);

CREATE TABLE auth_setup_lock (
    id SMALLINT PRIMARY KEY,
    lock_name VARCHAR(32) NOT NULL,
    CONSTRAINT uk_auth_setup_lock_name UNIQUE (lock_name)
);

